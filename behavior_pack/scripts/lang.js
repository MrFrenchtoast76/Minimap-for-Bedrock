export const LANGS = ["de", "en"];
export const LANG_NAMES = ["Deutsch", "English"];

export function t(lang, key, ...args) {
  const table = STRINGS[lang] ?? STRINGS.de;
  let s = table[key] ?? STRINGS.en[key] ?? key;
  for (const a of args) s = s.replace("%s", String(a));
  return s;
}

export function dimName(lang, dimId) {
  const short = dimId.replace("minecraft:", "");
  return t(lang, "dim_" + short);
}
